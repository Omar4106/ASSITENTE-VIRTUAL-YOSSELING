export function getArtifactLanguageInstruction(language: Language) {
  return language === 'en'
    ? 'Write all user-facing explanations and generated page copy in English, unless the user explicitly requests another language. Preserve exact brand names and requested titles.'
    : 'Redacta las explicaciones y el contenido visible de las páginas en español, salvo que el usuario solicite explícitamente otro idioma. Conserva exactamente los nombres de marca y títulos que pida.';
}
